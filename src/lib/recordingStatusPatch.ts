import { DEFAULT_FAILURE_REASON } from "./recordingAnnounce";
import type { RecordingStatusPayload, StreamStatus } from "./tauri";

/**
 * Що подія `recording-status` міняє в дзеркалі статусів.
 *
 * Живе тут, а не інлайном у `App.tsx`, заради сторожа. Обробник усередині
 * компонента не мав жодного тесту й не міг його мати без монтування всього
 * застосунку — а типи цю ваду не ловлять і не ловитимуть: дзеркало
 * оновлюється через `Partial<StreamStatus>`, тож патч, який поле просто не
 * згадає, компілюється мовчки. Саме так пара «спроба N з M» їхала в статусі
 * бекенда й не їхала в події.
 *
 * Функція чиста: усе, що вона кладе, приходить у самій події. Годинника тут
 * немає навмисно — `recordingStartedAt` бекенд знає точніше, бо ставить його в
 * мить, коли з'єднання стало записом, а не коли подія доїхала
 * (ADR 2026-09-15 «Подія несе те, що знає перехід» §1).
 */
export function recordingStatusPatch(payload: RecordingStatusPayload): Partial<StreamStatus> {
  return {
    // Подія несе результат запису, дзеркало зберігає стан потоку — два
    // словники, і вся межа між ними тут: «зупинено» — це результат, а стан
    // після нього — «очікування» (`tauri-ts-type-drift`, рішення 8).
    state: payload.status === "stopped" ? "idle" : payload.status,
    // Порожнеча в події — це скидання, а не «поле не згадали»: перехід, що не
    // є перепідключенням, стирає пару, а перехід, що не є записом, — мить
    // старту. Інваріанта «пара є тоді й лише тоді, коли перепідключення»
    // дзеркало не відтворює саме — воно повторює те, що сказав бекенд.
    reconnect: payload.reconnect,
    recordingStartedAt: payload.recordingStartedAt,
    // Бекенд, що прислав `error` без причини, має ваду — але мовчання сховало б
    // єдину подію, заради якої ця поверхня існує. Дефолт названий один раз, у
    // `recordingAnnounce`, і читається звідти.
    error: payload.status === "error" ? (payload.error ?? DEFAULT_FAILURE_REASON) : null,
  };
}
